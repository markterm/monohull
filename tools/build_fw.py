#!/usr/bin/env python3
"""Build Monohull for the FM-1 with JieLi's pi32v2 toolchain (Windows: C:/JL, as its installer
or innoextract puts it; JIELI_PI32 points elsewhere), and package it:

    python tools/build_fw.py            -> build/fw/monohull.bin      the app (XIP 0x02000120)
                                           build/fw/monohull_xip.bin  0x120 of padding first (fm1-emu --bin)
                                           build/fw/monohull.fwsc     the update package

The package is Felucca's: its update loader (ext/Felucca/firmware/loader, built here) and
tools/fm1pkg_make.py, which take three files of JieLi's AC79 SDK (Apache-2.0; fetched into
ext/ac79sdk and checked against the hashes Felucca's packages are made with).
SPDX-License-Identifier: GPL-3.0-only"""
import hashlib
import os
import subprocess
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FEL = ROOT / "ext" / "Felucca"
FW = FEL / "firmware"
OUT = ROOT / "build" / "fw"
TC = Path(os.environ.get("JIELI_PI32", "C:/JL/pi32"))
EXE = ".exe" if os.name == "nt" else ""
CLANG, LD, OBJCOPY, OBJDUMP, NM = (TC / "bin" / (n + EXE) for n in
                                   ("clang", "pi32v2-ld", "llvm-objcopy", "llvm-objdump", "pi32v2-nm"))
LIB = TC / "pi32v2-lib" / "r3"
BASE, SLOT = 0x02000120, 0x8DFBC
PRODUCT = "FM-1_928"            # Monohull's own identity (free in thefirmwarehub.com's catalogue, 2026-10-25)
DSP = ["mh_osc", "mh_resample", "mh_ladder", "mh_diode", "mh_svf", "mh_env", "mh_lfo", "mh_chorus", "mh_reverb", "mh_delay", "mh_ota", "mh_k35", "mh_synth", "mh_params",
       "mh_tables"]
CC = [str(CLANG), "-target", "pi32v2", "-mcpu=r3", "-mfprev1", "-ffp-contract=off"]
CF = ["-O2", "-ffunction-sections", "-fno-builtin", "-ffreestanding", "-Wall", "-Wno-unused-function",
      "-Wdouble-promotion", f"-I{TC / 'pi32v2-include'}"]
if os.environ.get("MH_PROFILE") == "1":       # per-stage timing in mh_prof (dsp/mh_synth.h)
    CF.append("-DMH_PROFILE")
if os.environ.get("MH_ONE_CORE") == "1":      # leave core 1 held (to compare)
    CF.append("-DMH_ONE_CORE")
if os.environ.get("MH_G") == "1":              # debug lines, for tools that map a pc to its source
    CF.append("-g")
if os.environ.get("MH_PIN_X"):                # hold the extras at a level (to measure it)
    CF.append("-DMH_PIN_X=" + str(int(os.environ["MH_PIN_X"])))
SDK_URL = "https://gitee.com/Jieli-Tech/fw-AC79_AIoT_SDK/raw/AC79NN_SDK_V1.2.1_2023-12-13/cpu/wl82/tools/"


def run(cmd, cwd=None):
    r = subprocess.run([str(c) for c in cmd], cwd=cwd, capture_output=True, text=True)
    if r.returncode:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit(f"build_fw: {Path(str(cmd[0])).name} failed")
    if r.stderr.strip():
        sys.stderr.write(r.stderr)
    return r.stdout


def assets(out):
    """an 8x12 bitmap font (Cascadia Mono, SIL OFL 1.1, from Windows' fonts), ASCII 32..126"""
    from PIL import Image, ImageDraw, ImageFont
    f = ImageFont.truetype(os.environ.get("MONOHULL_FONT", "C:/Windows/Fonts/CascadiaMono.ttf"), 11)
    rows = []
    for c in range(32, 127):
        im = Image.new("1", (8, 12), 0)
        ImageDraw.Draw(im).text((0, -1), chr(c), font=f, fill=1)
        for y in range(12):
            rows.append(sum(im.getpixel((x, y)) << (7 - x) for x in range(8)))
    out.write_text("/* generated by tools/build_fw.py: Cascadia Mono (SIL OFL 1.1), 8x12 */\n"
                   f"static const uint8_t FONT[95 * 12] = {{{','.join(map(str, rows))}}};\n")


def check_pages():
    """every parameter in dsp/mh_params.c must be on one of firmware/main.c's pages"""
    import re
    params = set(re.findall(r'^\s*[FI]\("(\w+)"', (ROOT / "dsp" / "mh_params.c").read_text(), re.M))
    for i in range(1, 9):
        params |= {f"mod{i}_src", f"mod{i}_dst", f"mod{i}_amount"}
    main = (ROOT / "firmware" / "main.c").read_text()
    paged = set(re.findall(r'"(\w+)"', main[main.index("PAGES[] = {"):main.index("#define NPAGES")]))
    missing = sorted(params - paged)
    if missing:
        raise SystemExit(f"build_fw: not on any page: {', '.join(missing)}")


def build_app():
    check_pages()
    OUT.mkdir(parents=True, exist_ok=True)
    assets(OUT / "assets.h")
    jobs = [CC + ["-c", FW / "crt0.S", "-o", OUT / "crt0.o"],
            CC + ["-c", FW / "hal" / "fm1_vec.S", "-o", OUT / "fm1_vec.o"],
            CC + ["-c", FW / "hal" / "fm1_isr.S", "-o", OUT / "fm1_isr.o"],
            CC + ["-c", ROOT / "firmware" / "fm1_cpu1.S", "-o", OUT / "fm1_cpu1.o"],
            CC + CF + [f"-I{FW / 'hal'}", f"-I{ROOT / 'dsp'}", f"-I{OUT}", "-c", ROOT / "firmware" / "main.c",
                       "-o", OUT / "main.o"],
            # USB and the update path at -Os: Dinghy's docs/API.md, USB-MIDI IN misbehaved built at -O2
            CC + [c if c != "-O2" else "-Os" for c in CF] + [f"-I{FW / 'hal'}", f'-DFELUCCA_ID="{PRODUCT}"', "-c",
                                                             ROOT / "firmware" / "usb_ota.c", "-o", OUT / "usb_ota.o"]]
    jobs += [CC + CF + ["-c", ROOT / "dsp" / f"{n}.c", "-o", OUT / f"{n}.o"] for n in DSP]
    with ThreadPoolExecutor(8) as ex:
        list(ex.map(run, jobs))
    objs = [OUT / f"{n}.o" for n in ["crt0", "fm1_vec", "fm1_isr", "fm1_cpu1", "main", "usb_ota", *DSP]]
    elf = OUT / "monohull.elf"
    run([LD, "--gc-sections", "-T", ROOT / "firmware" / "app.ld", "-e", "_start", *objs,
         "--start-group", LIB / "libm.a", LIB / "libc.a", LIB / "libcompiler_rt.a", "--end-group", "-o", elf])
    run([OBJCOPY, "-O", "binary", "-j", ".text", elf, OUT / "text.bin"])
    run([OBJCOPY, "-O", "binary", "-j", ".c1_text", elf, OUT / "c1.bin"])
    run([OBJCOPY, "-O", "binary", "-j", ".ram_text", elf, OUT / "rt.bin"])
    run([OBJCOPY, "-O", "binary", "-j", ".data", elf, OUT / "data.bin"])
    (OUT / "monohull.dis").write_text(run([OBJDUMP, "-d", elf]))
    nm = {}
    for ln in run([NM, elf]).splitlines():
        p = ln.split()
        if len(p) == 3:
            nm[p[2]] = int(p[0], 16)
    # each section at its load address in the flash: .text, core 1's waiting loop, the flash driver, .data
    img = bytearray()
    for name, at in (("text", BASE), ("c1", nm["_c1_load"]), ("rt", nm["_rt_load"]), ("data", nm["_data_load"])):
        part = (OUT / f"{name}.bin").read_bytes()
        assert at - BASE >= len(img), f"{name} overlaps the section before it"
        img += b"\xff" * (at - BASE - len(img)) + part
    img = bytes(img) + b"\xff" * (-len(img) % 4)
    assert nm["_start"] == BASE, hex(nm["_start"])
    assert img[:4] == bytes([0x04, 0x81, 0x80, 0x00]), img[:4].hex()
    assert len(img) <= SLOT, f"image {len(img)} > its slot ({SLOT})"
    (OUT / "monohull.bin").write_bytes(img)
    (OUT / "monohull_xip.bin").write_bytes(b"\0" * 0x120 + img)
    ram = nm["_bss_end"] - 0x01C08000
    print(f"{OUT / 'monohull.bin'}: {len(img)} bytes of the {SLOT} slot; RAM {ram} of 442368 bytes")
    return img


def sdk_files():
    sys.path.insert(0, str(FEL / "tools"))
    import build as felucca
    root = ROOT / "ext" / "ac79sdk"
    for rel, sha in felucca.SDK_SHA256.items():
        p = root / "cpu" / "wl82" / "tools" / rel
        if not p.exists() or hashlib.sha256(p.read_bytes()).hexdigest() != sha:
            p.parent.mkdir(parents=True, exist_ok=True)
            with urllib.request.urlopen(SDK_URL + rel, timeout=60) as r:
                p.write_bytes(r.read())
        if hashlib.sha256(p.read_bytes()).hexdigest() != sha:
            raise SystemExit(f"{p}: not the AC79NN_SDK_V1.2.1 file Felucca's packages are made with")
    os.environ["AC79_SDK"] = str(root)
    return felucca


def package(app):
    felucca = sdk_files()
    import fm1pkg_make as pkg
    tools = {"pi32v2/bin/clang": CLANG, "pi32v2/bin/ld": LD, "common/bin/objcopy": OBJCOPY,
             "common/bin/objdump": OBJDUMP}

    def tc(tool, *args):    # Felucca's helper, for the Windows toolchain's names
        rel = [str(Path(a).resolve().relative_to(felucca.SRC)) if isinstance(a, Path) else a for a in args]
        if tool == "cc":
            tool, rel = "pi32v2/bin/clang", ["-target", "pi32v2", *rel]
        return run([tools[tool], *rel], cwd=felucca.SRC)

    felucca.tc = tc
    ota = felucca.build_loader()
    data = pkg.ufw(pkg.flash_image(app, pkg.KEY), ota, PRODUCT)
    out = OUT / "monohull.fwsc"
    out.write_bytes(data)
    print(f"{out}: {len(data)} bytes, identity {PRODUCT}")


if __name__ == "__main__":
    package(build_app())
